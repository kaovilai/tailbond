// Package mqconf renders mqvpn INI files from tailbond settings and the mode table
// (docs/architecture.md, "Modes").
package mqconf

import (
	"fmt"
	"regexp"
	"strings"
)

// ModeSettings is one row of the contract's mode table.
type ModeSettings struct {
	Scheduler              string
	Hybrid                 bool
	Reorder                bool // [Reorder] on with a fiber_lte rule for inner QUIC
	Reinjection            string
	CC                     string // "" = mqvpn default (bbr2)
	Redundant              bool   // client only
	RequestServerScheduler bool   // client only
}

var modeTable = map[string]ModeSettings{
	"speed":     {Scheduler: "wlb", Hybrid: true, Reorder: true, Reinjection: "deadline", RequestServerScheduler: true},
	"streaming": {Scheduler: "wlb", Hybrid: true, Redundant: true, Reinjection: "idle", CC: "bbr"},
	"redundant": {Scheduler: "minrtt", Hybrid: true, Redundant: true, Reinjection: "idle", CC: "bbr", RequestServerScheduler: true},
	"failover":  {Scheduler: "minrtt", Reinjection: "off"},
}

func Mode(name string) (ModeSettings, error) {
	m, ok := modeTable[name]
	if !ok {
		return ModeSettings{}, fmt.Errorf("unknown mode %q", name)
	}
	return m, nil
}

var userRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$`)

// ValidUserName limits names to what is safe in INI values, URLs and file names.
func ValidUserName(s string) bool { return userRe.MatchString(s) }

type User struct{ Name, Key string }

type ServerParams struct {
	Port        int
	Subnet      string
	Subnet6     string
	TunName     string
	CertFile    string
	KeyFile     string
	Users       []User
	GlobalKey   string // only emitted when Users is empty (mqvpn needs some credential)
	Mode        string
	ControlAddr string
	LogLevel    string
	EgressAllow []string // hybrid TCP lane: private ranges the server may connect() to
}

type ClientParams struct {
	Server       string // host:port
	ServerName   string // SNI / verify name
	Insecure     bool
	Key          string
	DNS          []string
	Paths        []string
	TunName      string
	MTU          int
	Mode         string
	ControlAddr  string
	ManageRoutes bool
	KillSwitch   bool
	LogLevel     string
}

type iniWriter struct{ b strings.Builder }

func (w *iniWriter) section(name string) {
	if w.b.Len() > 0 {
		w.b.WriteByte('\n')
	}
	fmt.Fprintf(&w.b, "[%s]\n", name)
}

func (w *iniWriter) kv(k string, v any) {
	s := fmt.Sprint(v)
	// INI values are single-line; refuse to let a value smuggle in a new key.
	s = strings.NewReplacer("\n", " ", "\r", " ").Replace(s)
	fmt.Fprintf(&w.b, "%s = %s\n", k, s)
}

func boolStr(b bool) string {
	if b {
		return "true"
	}
	return "false"
}

func (w *iniWriter) multipath(m ModeSettings) {
	w.kv("Scheduler", m.Scheduler)
	if m.CC != "" {
		w.kv("CC", m.CC)
	}
	if m.Reinjection != "" {
		w.kv("Reinjection", m.Reinjection)
	}
}

// ReorderHeader is the bytes mqvpn's reorder stamp takes from each
// datagram (MQVPN_REORDER_HDR_LEN), in modes that reorder.
const ReorderHeader = 8

func (w *iniWriter) reorder(m ModeSettings) {
	if !m.Reorder {
		return
	}
	w.section("Reorder")
	w.kv("Enabled", "true")
	w.section("ReorderRule")
	w.kv("Proto", "udp")
	w.kv("Port", 443)
	w.kv("Profile", "fiber_lte")
	w.section("ReorderRule")
	w.kv("Proto", "udp")
	w.kv("Port", 53)
	w.kv("Profile", "default_udp")
}

const header = "# Generated by tailbondd from tailbond.json. Do not edit; changes are overwritten.\n"

// Server renders server.conf.
func Server(p ServerParams) (string, error) {
	m, err := Mode(p.Mode)
	if err != nil {
		return "", err
	}
	if p.CertFile == "" || p.KeyFile == "" {
		return "", fmt.Errorf("server needs a TLS cert and key")
	}
	if len(p.Users) == 0 && p.GlobalKey == "" {
		return "", fmt.Errorf("server needs at least one user or a global key")
	}
	w := &iniWriter{}
	w.section("Interface")
	w.kv("Listen", fmt.Sprintf("0.0.0.0:%d", p.Port))
	w.kv("Subnet", p.Subnet)
	if p.Subnet6 != "" {
		w.kv("Subnet6", p.Subnet6)
	}
	w.kv("TunName", orDefault(p.TunName, "tb0"))
	w.kv("LogLevel", orDefault(p.LogLevel, "info"))

	w.section("TLS")
	w.kv("Cert", p.CertFile)
	w.kv("Key", p.KeyFile)

	w.section("Auth")
	if len(p.Users) == 0 {
		w.kv("Key", p.GlobalKey)
	}
	for _, u := range p.Users {
		if !ValidUserName(u.Name) || u.Key == "" || strings.ContainsAny(u.Key, ": \t") {
			return "", fmt.Errorf("invalid user %q", u.Name)
		}
		w.kv("User", u.Name+":"+u.Key)
	}

	w.section("Multipath")
	w.multipath(m)
	// Lets each client's mode pick the download scheduler for its own session.
	w.kv("AllowClientScheduler", "true")

	if p.ControlAddr != "" {
		w.section("Control")
		w.kv("Listen", p.ControlAddr)
	}

	// Hybrid and reorder only take effect when the client enables them too, so
	// the server always offers both and the client's mode decides.
	w.section("Hybrid")
	w.kv("Enabled", "true")
	for _, c := range p.EgressAllow {
		w.kv("EgressAllow", c)
	}
	w.reorder(ModeSettings{Reorder: true})
	return header + w.b.String(), nil
}

// Client renders client.conf.
func Client(p ClientParams) (string, error) {
	m, err := Mode(p.Mode)
	if err != nil {
		return "", err
	}
	if p.Server == "" || p.Key == "" {
		return "", fmt.Errorf("client needs a server address and key (import a pairing first)")
	}
	w := &iniWriter{}
	w.section("Server")
	w.kv("Address", p.Server)
	if p.ServerName != "" {
		w.kv("ServerName", p.ServerName)
	}
	w.kv("Insecure", boolStr(p.Insecure))

	w.section("Auth")
	w.kv("Key", p.Key)

	w.section("Interface")
	w.kv("TunName", orDefault(p.TunName, "tb0"))
	if p.MTU > 0 {
		mtu := p.MTU
		if m.Reorder {
			// mqvpn caps first, then takes the reorder header off: ask for
			// the header on top, so the TUN gets p.MTU (IPv6 needs 1280)
			mtu += ReorderHeader
		}
		w.kv("MTU", mtu)
	}
	if len(p.DNS) > 0 {
		w.kv("DNS", strings.Join(p.DNS, ", "))
	}
	w.kv("LogLevel", orDefault(p.LogLevel, "info"))
	w.kv("ManageRoutes", boolStr(p.ManageRoutes))
	if p.KillSwitch {
		w.kv("KillSwitch", "true")
	}
	w.kv("Reconnect", "true")
	w.kv("ReconnectInterval", 3)

	w.section("Multipath")
	w.multipath(m)
	if m.Redundant {
		w.kv("Redundant", "true")
	}
	if m.RequestServerScheduler {
		w.kv("RequestServerScheduler", "true")
	}
	for _, path := range p.Paths {
		w.kv("Path", path)
	}

	// Upstream ignores [Control] in client mode; the tailbond patch serves
	// get_status/get_stats there.
	if p.ControlAddr != "" {
		w.section("Control")
		w.kv("Listen", p.ControlAddr)
	}

	if m.Hybrid {
		w.section("Hybrid")
		w.kv("Enabled", "true")
		w.kv("Tcp", "auto")
	}
	w.reorder(m)
	return header + w.b.String(), nil
}

func orDefault(s, d string) string {
	if s == "" {
		return d
	}
	return s
}
