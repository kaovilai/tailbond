"""Generate every platform's brand colours from assets/brand/tokens.json
(docs/brand.md), so they can't drift:

  assets/brand/tokens.css, agent/web/tokens.css     CSS custom properties
  android/.../ui/BrandTokens.kt                      Compose colours
  android/.../res/values{,-night}/brand_colors.xml   XML colours (icon, splash)
  ios/TailbondShare/BrandTokens.swift                SwiftUI colours
  ios/TailbondShare/Assets.xcassets/AccentColor...   the iOS accent colour
  GL panel + LuCI views                              an inline block between
                                                     brand-tokens:begin/end

  scripts/brand/gen-tokens.py           write them
  scripts/brand/gen-tokens.py --check   fail (exit 1) if any is out of date (CI)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
T = json.load(open(os.path.join(ROOT, "assets/brand/tokens.json")))
KINDS = ["wifi", "cellular", "ethernet", "usb", "shared-cellular", "tailnet"]
HEAD = "Generated by scripts/brand/gen-tokens.py from assets/brand/tokens.json; don't edit."


def low(c):
    return c.lower()


def camel(k):
    p = re.split(r"[-_]", k)
    return p[0] + "".join(x[:1].upper() + x[1:] for x in p[1:])


def pascal(k):
    c = camel(k)
    return c[:1].upper() + c[1:]


def rgb(c):
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))


# ---------------------------------------------------------------- CSS
def status(mode):
    """Status colours: the brand set on dark, darker shades on light (the
    brand set is under 3:1 on white; scripts/brand/contrast.py)."""
    return T["status"] if mode == "dark" else T["status-light"]


def css_scheme(mode):
    s, k = T["surface"][mode], T["connection"][mode]
    b = T["beam"][mode]
    v = [f"--tb-{n}: {low(s[n])};" for n in ["bg", "card", "text", "muted", "border", "primary", "on-primary"]]
    v.append(" ".join(f"--tb-{n}: {low(c)};" for n, c in status(mode).items()))
    v.append(f"--tb-beam: linear-gradient(90deg, {low(b[0])}, {low(b[1])});")
    v.append(f"--tb-beam-a: {low(b[0])}; --tb-beam-b: {low(b[1])};")
    v += [f"--tb-{'shared' if n == 'shared-cellular' else n}: {low(k[n])};" for n in KINDS]
    return v


def css():
    br = T["brand"]
    out = [f"/* tailbond design tokens (\"{T['palette']}\"). {HEAD}",
           "   Dark is the default; light applies with prefers-color-scheme or [data-theme=light]. */",
           ":root {"]
    out.append("  " + " ".join(f"--tb-{n}: {low(c)};" for n, c in br.items()))
    out.append(f"  --tb-radius-card: {T['radius']['card']}px; --tb-radius-control: {T['radius']['control']}px;")
    out.append(f"  --tb-font-sans: {T['font']['sans'].replace(chr(39), chr(34))};")
    out.append(f"  --tb-font-mono: {T['font']['mono'].replace(chr(39), chr(34))};")
    out += ["  " + x for x in css_scheme("dark")]
    out.append("}")
    light = "\n".join("    " + x for x in css_scheme("light"))
    out.append("\n@media (prefers-color-scheme: light) {\n  :root:not([data-theme=dark]) {\n" + light + "\n  }\n}")
    out.append("\n:root[data-theme=light] {\n" + light.replace("    ", "  ") + "\n}")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- Kotlin
def kt_color(c):
    return f"Color(0xFF{c.lstrip('#').upper()})"


def kotlin():
    out = ["// " + HEAD, "package dev.tailbond.app.ui", "", "import androidx.compose.ui.graphics.Color", "",
           f"/** \"{T['palette']}\" (docs/brand.md). */", "object BrandTokens {"]
    for n, c in T["brand"].items():
        out.append(f"    val {pascal(n)} = {kt_color(c)}")
    for mode in ("dark", "light"):
        M = pascal(mode)
        out.append("")
        out.append(f"    object {M} {{")
        for n, c in T["surface"][mode].items():
            out.append(f"        val {pascal(n)} = {kt_color(c)}")
        for n, c in status(mode).items():
            out.append(f"        val Status{pascal(n)} = {kt_color(c)}")
        a, b = T["beam"][mode]
        out.append(f"        val BeamStart = {kt_color(a)}")
        out.append(f"        val BeamEnd = {kt_color(b)}")
        for n in KINDS:
            out.append(f"        val {pascal(n)} = {kt_color(T['connection'][mode][n])}")
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def android_xml(mode):
    s = T["surface"][mode]
    out = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEAD} -->", "<resources>"]
    if mode == "light":
        out.append(f'    <color name="brand_ink">{T["brand"]["ink-950"]}</color>')
        out.append(f'    <color name="brand_volt">{T["brand"]["volt"]}</color>')
    for n in ["bg", "card", "text", "primary"]:
        out.append(f'    <color name="brand_{n.replace("-", "_")}">{s[n]}</color>')
    out.append("</resources>")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- Swift
def sw_color(c):
    r, g, b = rgb(c)
    return f"Color(red: {r / 255:.4f}, green: {g / 255:.4f}, blue: {b / 255:.4f})"


def swift():
    out = ["// " + HEAD, "import SwiftUI", "", f"/// \"{T['palette']}\" (docs/brand.md).", "enum BrandTokens {"]
    for n, c in T["brand"].items():
        out.append(f"    static let {camel(n)} = {sw_color(c)}")
    for mode in ("dark", "light"):
        out.append("")
        out.append(f"    enum {pascal(mode)} {{")
        for n, c in T["surface"][mode].items():
            out.append(f"        static let {camel(n)} = {sw_color(c)}")
        for n, c in status(mode).items():
            out.append(f"        static let status{pascal(n)} = {sw_color(c)}")
        a, b = T["beam"][mode]
        out.append(f"        static let beam = [{sw_color(a)}, {sw_color(b)}]")
        for n in KINDS:
            out.append(f"        static let {camel(n)} = {sw_color(T['connection'][mode][n])}")
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def accent_colorset():
    def comp(c):
        r, g, b = rgb(c)
        return {"color-space": "srgb", "components": {"alpha": "1.000", "red": f"{r / 255:.3f}", "green": f"{g / 255:.3f}", "blue": f"{b / 255:.3f}"}}
    return json.dumps({
        "colors": [
            {"idiom": "universal", "color": comp(T["surface"]["light"]["primary"])},
            {"idiom": "universal", "appearances": [{"appearance": "luminosity", "value": "dark"}], "color": comp(T["surface"]["dark"]["primary"])},
        ],
        "info": {"author": "xcode", "version": 1},
    }, indent=2) + "\n"


# ---------------------------------------------------------------- GL panel / LuCI (light: GL's admin is light)
def inline_vars():
    s, k, b = T["surface"]["light"], T["connection"]["light"], T["beam"]["light"]
    v = [f"--tb-primary:{low(s['primary'])}", f"--tb-on-primary:{low(s['on-primary'])}", f"--tb-ink:{low(T['brand']['ink-950'])}",
         f"--tb-teal:{low(T['brand']['teal-600'])}", f"--tb-volt:{low(T['brand']['volt-dark'])}",
         f"--tb-beam:linear-gradient(90deg,{low(b[0])},{low(b[1])})",
         f"--tb-ok:{low(T['status-light']['ok'])}", f"--tb-warn:{low(T['status-light']['warn'])}", f"--tb-error:{low(T['status-light']['error'])}"]
    v += [f"--tb-{'shared' if n == 'shared-cellular' else n}:{low(k[n])}" for n in KINDS]
    return ";".join(v)


def replace_block(text, start, end, body):
    i, j = text.find(start), text.find(end)
    if i < 0 or j < 0:
        raise SystemExit(f"markers {start} … {end} not found")
    return text[: i + len(start)] + body + text[j:]


def gl_panel(text):
    return replace_block(text, "/*brand-tokens:begin*/", "/*brand-tokens:end*/", f'".tb{{{inline_vars()};}}",')


def luci(text):
    return replace_block(text, "/*brand-tokens:begin*/", "/*brand-tokens:end*/", f"'{inline_vars()}'")


# ----------------------------------------------------------------
FILES = {
    "assets/brand/tokens.css": lambda _: css(),
    "agent/web/tokens.css": lambda _: css(),
    "android/app/src/main/kotlin/dev/tailbond/app/ui/BrandTokens.kt": lambda _: kotlin(),
    "android/app/src/main/res/values/brand_colors.xml": lambda _: android_xml("light"),
    "android/app/src/main/res/values-night/brand_colors.xml": lambda _: android_xml("dark"),
    "ios/TailbondShare/BrandTokens.swift": lambda _: swift(),
    "ios/TailbondShare/Assets.xcassets/AccentColor.colorset/Contents.json": lambda _: accent_colorset(),
    "packaging/openwrt/gl-ui/www/views/gl-sdk4-ui-tailbond.common.js": gl_panel,
    "packaging/openwrt/luci/www/luci-static/resources/view/tailbond.js": luci,
}


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, gen in FILES.items():
        p = os.path.join(ROOT, rel)
        cur = open(p).read() if os.path.exists(p) else None
        new = gen(cur)
        if cur == new:
            continue
        if check:
            stale.append(rel)
            continue
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(new)
        print("wrote", rel)
    if stale:
        print("brand tokens out of date (run scripts/brand/gen-tokens.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
