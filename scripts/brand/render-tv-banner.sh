#
# The Android TV launcher banner (docs/brand.md, docs/android.md "Android
# TV"): assets/brand/tailbond-wordmark-dark.svg on brand ink with the
# beam bar of the social preview, as a vector drawable, so it stays out of
# the rasters in git like the launcher icon:
#
#   android/app/src/main/res/drawable/tv_banner.xml
#       320x180 at xhdpi (160x90dp), what the TV home screen shows
#
# A vector drawable can't draw text, so the wordmark's "tail" and "bond"
# are Inter's own glyph outlines (Regular and ExtraBold, the weights of
# the SVG), read with fontTools in an Alpine container (podman), so every
# machine makes the same file.
#
#   scripts/brand/render-tv-banner.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PODMAN="${PODMAN:-podman}"
IMAGE="${TB_ALPINE_IMAGE:-docker.io/library/alpine:3.20}"
OUT=android/app/src/main/res/drawable/tv_banner.xml

"$PODMAN" run --rm -i -v "$ROOT:/repo:z" -w /repo -e OUT="$OUT" "$IMAGE" sh -euc '
  apk add --no-cache python3 py3-fonttools font-inter >/dev/null
  python3 - "$OUT"
' <<'PY'
import sys
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

FONTS = "/usr/share/fonts/inter/"
# assets/brand/tailbond-wordmark-dark.svg: <text x="76" y="43" font-size="34"
# letter-spacing="-0.5">tail<tspan font-weight="800">bond</tspan></text>
X0, BASE, SIZE, SPACING = 76.0, 43.0, 34.0, -0.5


def num(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


def run(text, font, x):
    """The glyph outlines of text in the wordmark's units, and where it ends."""
    f = TTFont(FONTS + font)
    glyphs, cmap = f.getGlyphSet(), f.getBestCmap()
    s = SIZE / f["head"].unitsPerEm
    pen = SVGPathPen(glyphs, ntos=num)
    for ch in text:
        g = glyphs[cmap[ord(ch)]]
        g.draw(TransformPen(pen, (s, 0, 0, -s, x, BASE)))
        x += g.width * s + SPACING
    return pen.getCommands(), x


tail, x_bond = run("tail", "Inter-Regular.otf", X0)
bond, x_end = run("bond", "Inter-ExtraBold.otf", x_bond)

# the wordmark (mark + text) centred on the 320x180 banner, above the beam bar
W, H, BAR = 320, 180, 8
scale = 248 / x_end
tx, ty = (W - x_end * scale) / 2, (H - BAR - 64 * scale) / 2

dot = "M{0},{1} a3.6,3.6 0 1,0 7.2,0 a3.6,3.6 0 1,0 -7.2,0"
xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/brand/render-tv-banner.sh from
     assets/brand/tailbond-wordmark-dark.svg: don't edit by hand.
     The Android TV launcher banner (320x180 at xhdpi). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="160dp"
    android:height="90dp"
    android:viewportWidth="{W}"
    android:viewportHeight="{H}">
  <path android:pathData="M0,0 H{W} V{H} H0 Z" android:fillColor="#071A1D" />
  <path android:pathData="M0,{H - BAR} H{W} V{H} H0 Z">
    <aapt:attr name="android:fillColor">
      <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="{W}" android:endY="0"
          android:startColor="#2DD4BF" android:endColor="#C6F432" />
    </aapt:attr>
  </path>
  <group android:translateX="{num(tx)}" android:translateY="{num(ty)}" android:scaleX="{num(scale)}" android:scaleY="{num(scale)}">
    <path android:pathData="M12,18 C26,18 28,32 38,32" android:strokeColor="#38BDF8" android:strokeWidth="4.5" android:strokeLineCap="round" />
    <path android:pathData="M12,46 C26,46 28,32 38,32" android:strokeColor="#A78BFA" android:strokeWidth="4.5" android:strokeLineCap="round" />
    <path android:pathData="M12,32 H38" android:strokeColor="#2DD4BF" android:strokeWidth="4.5" android:strokeLineCap="round" />
    <path android:pathData="M36,32 H50" android:strokeWidth="8" android:strokeLineCap="round">
      <aapt:attr name="android:strokeColor">
        <gradient android:type="linear" android:startX="36" android:startY="32" android:endX="50" android:endY="32"
            android:startColor="#2DD4BF" android:endColor="#C6F432" />
      </aapt:attr>
    </path>
    <path android:pathData="M45,23 L54,32 L45,41" android:strokeColor="#C6F432" android:strokeWidth="5" android:strokeLineCap="round" android:strokeLineJoin="round" />
    <path android:pathData="{dot.format(8.4, 18)}" android:fillColor="#38BDF8" />
    <path android:pathData="{dot.format(8.4, 32)}" android:fillColor="#2DD4BF" />
    <path android:pathData="{dot.format(8.4, 46)}" android:fillColor="#A78BFA" />
    <path android:pathData="{tail}" android:fillColor="#E6FFFA" />
    <path android:pathData="{bond}">
      <aapt:attr name="android:fillColor">
        <gradient android:type="linear" android:startX="{num(x_bond)}" android:startY="0" android:endX="{num(x_end)}" android:endY="0"
            android:startColor="#2DD4BF" android:endColor="#C6F432" />
      </aapt:attr>
    </path>
  </group>
</vector>
"""
with open(sys.argv[1], "w") as f:
    f.write(xml)
print("rendered:", sys.argv[1])
PY
